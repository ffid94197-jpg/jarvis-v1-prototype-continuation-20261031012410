"""Explicitly approved Windows desktop launch catalog for the JARVIS local sidecar.

No arbitrary program names, shell command strings, downloaded executables,
network paths, batch files, or model-selected executables are accepted.
The operator may extend the catalog by editing approved_apps.json outside the
agent's writable workspace. Those entries are not generated by the model.
"""
import json
import ntpath
import os
import re
from pathlib import Path

BUILTINS = ('settings', 'chrome', 'edge', 'firefox', 'vscode', 'notepad',
            'calculator', 'explorer', 'paint', 'tlauncher')
SETTINGS_PAGES = {
    'home': 'ms-settings:',
    'display': 'ms-settings:display',
    'sound': 'ms-settings:sound',
    'network': 'ms-settings:network',
    'wifi': 'ms-settings:network-wifi',
    'bluetooth': 'ms-settings:bluetooth',
    'apps': 'ms-settings:appsfeatures',
    'updates': 'ms-settings:windowsupdate',
    'privacy': 'ms-settings:privacy',
    'storage': 'ms-settings:storagesense',
    'power': 'ms-settings:powersleep',
    'accounts': 'ms-settings:yourinfo',
    'personalization': 'ms-settings:personalization',
    'time': 'ms-settings:dateandtime',
}
BLOCKED = frozenset({'cmd.exe','powershell.exe','pwsh.exe','wscript.exe','cscript.exe',
  'mshta.exe','rundll32.exe','reg.exe','regedit.exe','taskkill.exe','wmic.exe',
  'schtasks.exe','python.exe','node.exe','bash.exe','wsl.exe','robocopy.exe'})
ALIAS = re.compile(r'^[a-z][a-z0-9_-]{1,31}$')

def safe_executable_path(value):
    if not isinstance(value,str) or len(value)>400 or not re.match(r'^[a-zA-Z]:\\',value):
        return False
    normalized=ntpath.normpath(value)
    if normalized!=value or not value.lower().endswith('.exe') or '\\..\\' in value or ':' in value[2:]:
        return False
    if ntpath.basename(value).lower() in BLOCKED:
        return False
    return True

def approved_config(config_file=None):
    config=Path(config_file) if config_file else Path(__file__).with_name('approved_apps.json')
    if not config.exists():return {}
    try:
        raw=json.loads(config.read_text(encoding='utf-8'))
        if not isinstance(raw,dict) or len(raw)>40: return {}
        out={}
        for alias,path in raw.items():
            if isinstance(alias,str) and ALIAS.fullmatch(alias) and alias not in BUILTINS and safe_executable_path(path):
                out[alias]=path
        return out
    except (ValueError,OSError,UnicodeError):return {}

def app_aliases(config_file=None):
    return tuple(BUILTINS)+tuple(approved_config(config_file))

def candidates(alias,env=None):
    e=os.environ if env is None else env
    pf=e.get('ProgramFiles') or e.get('PROGRAMFILES') or r'C:\Program Files'
    pf86=e.get('ProgramFiles(x86)') or e.get('PROGRAMFILES(X86)') or r'C:\Program Files (x86)'
    local=e.get('LOCALAPPDATA') or ''
    windir=e.get('SystemRoot') or e.get('WINDIR') or r'C:\Windows'
    sys32=ntpath.join(windir,'System32')
    if alias in ('notepad','calculator','explorer','paint'):
        return [ntpath.join(windir,'explorer.exe')] if alias=='explorer' else [
            ntpath.join(sys32, {'notepad':'notepad.exe','calculator':'calc.exe','paint':'mspaint.exe'}[alias])]
    if alias=='chrome':
        return [ntpath.join(pf,'Google','Chrome','Application','chrome.exe'),
                ntpath.join(pf86,'Google','Chrome','Application','chrome.exe'),
                ntpath.join(local,'Google','Chrome','Application','chrome.exe')]
    if alias=='edge':
        return [ntpath.join(pf86,'Microsoft','Edge','Application','msedge.exe'),
                ntpath.join(pf,'Microsoft','Edge','Application','msedge.exe')]
    if alias=='firefox':
        return [ntpath.join(pf,'Mozilla Firefox','firefox.exe'),
                ntpath.join(pf86,'Mozilla Firefox','firefox.exe')]
    if alias=='vscode':
        return [ntpath.join(local,'Programs','Microsoft VS Code','Code.exe'),
                ntpath.join(pf,'Microsoft VS Code','Code.exe')]
    if alias=='tlauncher':
        return [e.get('JARVIS_TLAUNCHER_PATH','')]
    return [approved_config().get(alias,'')]

def resolve_app(alias,env=None,exists=None):
    if alias=='settings':return {'kind':'settings','target':SETTINGS_PAGES['home']}
    if alias not in app_aliases():return None
    check=exists or (lambda p: Path(p).is_file())
    for path in candidates(alias,env):
        if safe_executable_path(path) and check(path):
            return {'kind':'exe','target':path}
    return None
