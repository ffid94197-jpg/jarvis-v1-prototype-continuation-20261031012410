'use strict';
const assert=require('node:assert/strict');
const {confirmedMove}=require('./movement_proof.cjs');
const {findExposedOre}=require('./ore_access.cjs');
const from={x:0.5,y:16,z:0.5},target={x:1,y:16,z:0};
let n=0; const test=(yes,msg)=>{assert.ok(yes,msg);n++;};
test(!confirmedMove(from,from,target),'No movement cannot count as tunnel advance');
test(confirmedMove(from,{x:1.5,y:16,z:.5},target),'Observed movement near target counts');
test(!confirmedMove(from,{x:0.6,y:16,z:.5},target),'Small position jitter rejected');
test(!confirmedMove(from,{x:20,y:16,z:0},target),'Far-away displacement is not target advance');
test(!confirmedMove(from,{x:NaN,y:16,z:0},target),'Malformed position rejected');
test(!confirmedMove(null,{x:1.5,y:16,z:.5},target),'Missing starting position rejected');
const ore={name:'deepslate_diamond_ore',position:{x:0,y:-50,z:0}};
const stone={name:'deepslate',boundingBox:'block'};
const air={name:'air',boundingBox:'empty'};
const at=p=>p.x===0&&p.y===-50&&p.z===0?ore:stone;
const buried={findBlocks:()=>[ore.position],blockAt:at};
test(findExposedOre(buried,[ore.name])===null,'Loaded but buried ore must not count as exposed');
const exposed={findBlocks:()=>[ore.position],blockAt:p=>(p.x===1 && (p.y===-50||p.y===-49))?air:at(p)};
test(!!findExposedOre(exposed,[ore.name]),'Accessible cave-face ore is recognized');
console.log(`REAL_PROGRESS ${n}/${n} PASS (offline movement and ore accessibility)`);
