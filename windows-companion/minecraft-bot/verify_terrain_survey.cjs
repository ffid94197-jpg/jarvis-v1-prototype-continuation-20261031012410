'use strict';
const assert=require('node:assert/strict');
const {planSurveyStep}=require('./terrain_survey.cjs');
let n=0;
const test=(statement)=>{assert.ok(statement);n++;};
const at=(x,y,z)=>({name:y<94?'stone':'air',boundingBox:y<94?'block':'empty',position:{x,y,z}});
const src={position:{x:0,y:94,z:0},ore:'diamond',index:0,getBlock:at};
let r=planSurveyStep(src);
test(r.ok&&r.down&&r.target.y===93&&r.dig.length===1);
test(r.dig[0].name==='stone');
test(planSurveyStep({...src,ore:'iron'}).ok);
test(planSurveyStep({...src,ore:'bad'}).ok===false);
test(planSurveyStep({...src,getBlock:()=>null}).ok===false);
const alternate=planSurveyStep({...src,getBlock:(x,y,z)=>x===2&&y===93?{name:'lava',boundingBox:'empty'}:at(x,y,z)});
test(alternate.ok&&alternate.attemptedDirections>1&&alternate.target.x!==1);
test(planSurveyStep({...src,getBlock:(x,y,z)=>x===1&&y===93?{name:'chest',boundingBox:'block'}:at(x,y,z)}).ok===true);
test(!planSurveyStep({...src,getBlock:(x,y,z)=>(y===93&&(Math.abs(x)+Math.abs(z))>=1)?{name:'lava',boundingBox:'empty'}:at(x,y,z)}).ok);
const deep=planSurveyStep({...src,position:{x:0,y:-54,z:0},getBlock:(x,y,z)=>({name:'deepslate',boundingBox:'block',position:{x,y,z}})});
test(deep.ok&&deep.down===false&&deep.target.y===-54);
console.log('TERRAIN_SURVEY '+n+'/'+n+' PASS (offline decision checks, not server navigation)');
